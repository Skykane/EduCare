// Picks an icon from the category name (used when a request has no photo).
function categoryIcon(name) {
  const n = String(name || '').toLowerCase();
  if (/network|wifi|router/.test(n)) return 'wifi';
  if (/computer|it\b|laptop|printer/.test(n)) return 'monitor';
  if (/electric|light|power/.test(n)) return 'zap';
  if (/air|aircon|ventil/.test(n)) return 'wind';
  if (/lab|science/.test(n)) return 'flask';
  if (/audio|visual|projector|tv/.test(n)) return 'video';
  if (/furniture|fixture|chair|table/.test(n)) return 'sofa';
  return 'wrench';
}

